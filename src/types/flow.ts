// === CONDITION RULE TYPES ===

export type ConditionRuleType =
  | 'tag'
  | 'pipeline'
  | 'assigned'
  | 'variable'
  | 'contact_field'
  | 'service_mode';

export type ConditionOperator =
  | 'equals'
  | 'not_equals'
  | 'contains'
  | 'not_contains'
  | 'greater_than'
  | 'less_than'
  | 'exists'
  | 'not_exists';

export interface ConditionRule {
  id: string;
  type: ConditionRuleType;
  negate?: boolean;
  // For tag
  tagId?: string;
  // For pipeline
  pipelineId?: string;
  columnId?: string;
  // For assigned
  userId?: string;
  // For variable
  variable?: string;
  operator?: ConditionOperator;
  value?: string;
  // For contact_field: 'name' | 'email' | 'phone' são colunas de contacts;
  // qualquer outra string é a `key` de um campo personalizado da org, lido de
  // contacts.metadata.custom_fields.
  contactField?: string;
  // For service_mode: os quatro primeiros são o enum service_mode do banco.
  // pending/bot/human são o que a tela gravava antes de bater com o enum —
  // ficam aceitos porque há fluxo salvo com eles.
  serviceMode?: 'pendente' | 'ia' | 'ativo' | 'arquivado' | 'pending' | 'bot' | 'human';
}

// === CONSULTAR CONTATOS ===

export type ContactQueryFilterType = 'tag' | 'pipeline' | 'custom_field';

export type ContactQueryOperator =
  | 'equals'
  | 'not_equals'
  | 'contains'
  | 'is_empty'
  | 'is_not_empty';

export interface ContactQueryFilter {
  id: string;
  type: ContactQueryFilterType;
  /** Só para tag e pipeline: inverte ("não tem a tag", "não está na etapa"). */
  negate?: boolean;
  tagId?: string;
  pipelineId?: string;
  columnId?: string;
  /** Só para custom_field: a `key` do campo personalizado. */
  fieldKey?: string;
  /**
   * A tela troca o seletor por um campo de texto: o id da tag/etapa ou a chave
   * do campo vem de {{variavel}}, resolvida na execução. O motor interpola os
   * três sempre, então isto aqui é só a afordância da tela.
   */
  useVariable?: boolean;
  operator?: ContactQueryOperator;
  value?: string;
}

export interface ContactQueryConfig {
  /**
   * 'count' devolve um número; 'list' devolve texto com os campos escolhidos;
   * 'group' devolve uma linha "valor | contagem" por valor do campo escolhido —
   * exatamente o formato que o bloco [[GRAFICO]] do gerador de PDF lê.
   */
  queryMode: 'count' | 'list' | 'group';
  filters: ContactQueryFilter[];
  /** Só para 'group': a `key` do campo personalizado que vira as linhas. */
  groupByField?: string;
  /** Afordância da tela: troca o seletor do campo de agrupamento por {{variavel}}. */
  groupByUseVariable?: boolean;
  /**
   * Valores esperados, na ordem em que devem aparecer. Preenchido, a saída
   * respeita essa ordem e MOSTRA OS ZEROS — opção que ninguém escolheu sumindo
   * do gráfico parece que a pergunta não foi feita. Valor que apareceu e não
   * está aqui entra depois, por contagem: é assim que uma opção nova na
   * pesquisa aparece sozinha em vez de o relatório mentir calado.
   */
  groupExpectedValues?: string[];
  /** Acrescenta uma linha "(nao respondeu) | n" no fim. Fora por padrão. */
  groupIncludeEmpty?: boolean;
  /** Campos concatenados em cada linha da listagem: 'name' | 'phone' | 'email' | key de campo personalizado. */
  listFields: string[];
  listLimit: number;
  /** Nome da variável de fluxo onde o resultado é gravado. */
  outputVariable: string;
}

